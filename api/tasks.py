"""
Background Celery tasks for RetainIQ retention automation.

The worker:
  1. Receives a job with (customer_id, task_id).
  2. Opens its own SQLAlchemy session (never reuses FastAPI's).
  3. Fetches the customer and retention task.
  4. Generates a personalised email from the SHAP reasons in the task description.
  5. Calls email_service.send_email (dev mode: logs to console).
  6. Updates email_status → "sent" or "failed".
  7. Closes the session in the finally block.
"""

import os
import logging
from api.celery_app import celery_app
from api.database import SessionLocal
from api.models import RetentionTask, Customer
from api.email_service import send_email

logger = logging.getLogger(__name__)


import re

def _clean_reason(reason_text: str) -> str:
    """Strip out the technical numbers and percentages from SHAP reasons."""
    # Convert "payment_amount is 131% above average (150.0 vs avg 64.9), which increases churn risk." -> "High payment amount"
    reason = reason_text.lower()
    if "payment_amount" in reason:
        return "High payment amount" if "above" in reason else "Low payment amount"
    if "support_ticket_volume" in reason:
        return "High support ticket volume" if "above" in reason else "Low support ticket volume"
    if "login_frequency" in reason:
        return "High login frequency" if "above" in reason else "Low login frequency"
    if "feature_usage" in reason:
        return "High feature usage" if "above" in reason else "Low feature usage"
    if "account_age" in reason:
        return "Low account age" if "below" in reason else "High account age"
    return reason_text.split(',')[0].capitalize()

def _build_email_body(customer_name: str, reasons_text: str) -> str:
    """Return a retention email body matching the required format."""
    name = customer_name or "Valued Customer"
    
    # Extract probability from "Churn probability: 82.0%. Main risk reasons: ..."
    prob_match = re.search(r'Churn probability: ([\d.]+)%', reasons_text)
    prob_str = f"{prob_match.group(1)}%" if prob_match else ">= 70%"
    
    # Extract reasons
    reasons_part = reasons_text.split('Main risk reasons:')[-1].strip()
    raw_reasons = [r.strip() for r in reasons_part.split(' risk.') if r.strip()]
    cleaned_reasons = [_clean_reason(r) for r in raw_reasons]
    
    lines = [
        f"Hello {name},",
        "",
        "RetainIQ has identified this customer account as high risk.",
        "",
        f"Churn Probability: {prob_str}",
        "Risk Level: HIGH",
        "",
        "Main contributing factors:"
    ]
    
    for r in cleaned_reasons:
        if r:
            lines.append(f"- {r.capitalize()}")
            
    lines += [
        "",
        "Recommended action: Contact the customer and provide personalized support.",
        "",
        "This message was generated by RetainIQ."
    ]
    return "\n".join(lines)


@celery_app.task(bind=True, max_retries=3, default_retry_delay=60)
def send_retention_email_task(self, customer_id: int, task_id: int):
    """
    Celery task: send a personalised retention email to a high-risk customer.
    Safe to retry on transient SMTP failures.
    Marks email_status='failed' after max retries are exhausted.
    """
    db = SessionLocal()
    try:
        task = db.query(RetentionTask).filter(RetentionTask.id == task_id).first()
        customer = db.query(Customer).filter(Customer.id == customer_id).first()

        if not task:
            logger.warning("RetentionTask %s not found — skipping.", task_id)
            return "task_not_found"
        if not customer:
            logger.warning("Customer %s not found — skipping.", customer_id)
            task.email_status = "failed"
            db.commit()
            return "customer_not_found"

        # Already successfully sent — do not re-send
        if task.email_status == "sent":
            return "already_sent"

        body = _build_email_body(customer.name or "", task.description or "")
        subject = "We'd love to help you get more from RetainIQ"

        # Email destination: use RETENTION_TEST_EMAIL override for testing,
        # otherwise use the customer's real email.
        test_email = os.environ.get("RETENTION_TEST_EMAIL", "").strip()
        if test_email:
            to_email = test_email
            logger.info("Test override: Sending to %s instead of customer email", to_email)
        elif customer.email and customer.email.strip():
            to_email = customer.email.strip()
            logger.info("Destination: customer email for customer id=%s", customer_id)
        else:
            task.email_status = "missing_recipient"
            db.commit()
            logger.warning("No email for customer %s — marking as missing_recipient", customer_id)
            return "missing_recipient"

        status_result = send_email(to_email, subject, body)
        task.email_status = status_result
        db.commit()

        logger.info("Retention email for customer %s -> %s", customer_id, status_result)

        # Raise so Celery retries if delivery failed or SMTP not configured
        if status_result in ("failed", "not_configured"):
            raise RuntimeError(f"Email delivery returned status '{status_result}' — will retry")

        return status_result

    except self.MaxRetriesExceededError:
        # Final failure — mark as failed in a fresh session to avoid stale state
        logger.error("Max retries exceeded for task %s — marking as failed", task_id)
        db.close()
        fresh_db = SessionLocal()
        try:
            t = fresh_db.query(RetentionTask).filter(RetentionTask.id == task_id).first()
            if t and t.email_status not in ("sent",):
                t.email_status = "failed"
                fresh_db.commit()
        finally:
            fresh_db.close()
        return "failed"

    except Exception as exc:
        db.rollback()
        logger.exception("Error in send_retention_email_task for task %s: %s", task_id, exc)

        # Try to mark the task as retrying in a fresh session
        db.close()
        fresh_db = SessionLocal()
        try:
            t = fresh_db.query(RetentionTask).filter(RetentionTask.id == task_id).first()
            if t and t.email_status not in ("sent",):
                t.email_status = "queued"  # still queued — retry pending
                fresh_db.commit()
        except Exception:
            pass
        finally:
            fresh_db.close()

        raise self.retry(exc=exc)

    finally:
        try:
            db.close()
        except Exception:
            pass
